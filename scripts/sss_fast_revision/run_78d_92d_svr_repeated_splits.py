def recover_raw_features(
    path: Path,
    expected_features: int,
) -> tuple[
    np.ndarray,
    np.ndarray,
    dict[str, Any],
]:
    """
    Recover complete raw descriptor matrix in original canonical order.

    Preferred:
        F_train_raw / F_val_raw / F_test_raw

    Fallback:
        inverse standardisation using stored mean/std.

    Never random-split already-standardised canonical F_* directly.
    """
    if not path.is_file():
        raise FileNotFoundError(path)

    required = {
        "F_train",
        "F_val",
        "F_test",
        "y_train",
        "y_val",
        "y_test",
    }

    with np.load(
        path,
        allow_pickle=False,
    ) as data:

        missing = sorted(
            required
            - set(data.files)
        )

        if missing:
            raise KeyError(
                f"{path} missing arrays: {missing}"
            )

        F_train = np.asarray(
            data["F_train"],
            dtype=np.float64,
        )

        F_val = np.asarray(
            data["F_val"],
            dtype=np.float64,
        )

        F_test = np.asarray(
            data["F_test"],
            dtype=np.float64,
        )

        y_train = np.asarray(
            data["y_train"],
            dtype=np.float64,
        )

        y_val = np.asarray(
            data["y_val"],
            dtype=np.float64,
        )

        y_test = np.asarray(
            data["y_test"],
            dtype=np.float64,
        )

        raw_keys = {
            "F_train_raw",
            "F_val_raw",
            "F_test_raw",
        }

        metadata: dict[str, Any] = {}

        if raw_keys.issubset(
            set(data.files)
        ):
            raw_train = np.asarray(
                data["F_train_raw"],
                dtype=np.float64,
            )

            raw_val = np.asarray(
                data["F_val_raw"],
                dtype=np.float64,
            )

            raw_test = np.asarray(
                data["F_test_raw"],
                dtype=np.float64,
            )

            metadata[
                "reconstruction_mode"
            ] = "explicit_raw_arrays"

        else:
            mean_candidates = [
                "feature_mean",
                "feature_means",
                "F_mean",
                "train_feature_mean",
                "mean",
            ]

            std_candidates = [
                "feature_std",
                "feature_stds",
                "F_std",
                "train_feature_std",
                "std",
            ]

            feature_mean = None
            mean_key = None

            for key in mean_candidates:
                if key in data.files:
                    candidate = np.asarray(
                        data[key]
                    )

                    if (
                        candidate.ndim == 1
                        and candidate.shape[0]
                        == expected_features
                        and np.issubdtype(
                            candidate.dtype,
                            np.number,
                        )
                    ):
                        feature_mean = np.asarray(
                            candidate,
                            dtype=np.float64,
                        )

                        mean_key = key
                        break

            feature_std = None
            std_key = None

            for key in std_candidates:
                if key in data.files:
                    candidate = np.asarray(
                        data[key]
                    )

                    if (
                        candidate.ndim == 1
                        and candidate.shape[0]
                        == expected_features
                        and np.issubdtype(
                            candidate.dtype,
                            np.number,
                        )
                    ):
                        feature_std = np.asarray(
                            candidate,
                            dtype=np.float64,
                        )

                        std_key = key
                        break

            if (
                feature_mean is None
                or feature_std is None
            ):
                # Flexible fallback: look for one numeric vector
                # containing "mean"/"std" in its array name.
                possible_means = []
                possible_stds = []

                for key in data.files:
                    try:
                        candidate = np.asarray(
                            data[key]
                        )
                    except Exception:
                        continue

                    if not (
                        candidate.ndim == 1
                        and candidate.shape[0]
                        == expected_features
                        and np.issubdtype(
                            candidate.dtype,
                            np.number,
                        )
                    ):
                        continue

                    if "mean" in key.lower():
                        possible_means.append(
                            (
                                key,
                                candidate,
                            )
                        )

                    if "std" in key.lower():
                        possible_stds.append(
                            (
                                key,
                                candidate,
                            )
                        )

                if (
                    feature_mean is None
                    and len(
                        possible_means
                    ) == 1
                ):
                    mean_key = (
                        possible_means[
                            0
                        ][0]
                    )

                    feature_mean = np.asarray(
                        possible_means[
                            0
                        ][1],
                        dtype=np.float64,
                    )

                if (
                    feature_std is None
                    and len(
                        possible_stds
                    ) == 1
                ):
                    std_key = (
                        possible_stds[
                            0
                        ][0]
                    )

                    feature_std = np.asarray(
                        possible_stds[
                            0
                        ][1],
                        dtype=np.float64,
                    )

            if (
                feature_mean is None
                or feature_std is None
            ):
                raise RuntimeError(
                    "Cannot recover raw features from "
                    f"{path}. Available keys: "
                    f"{sorted(data.files)}"
                )

            raw_train = (
                F_train
                * feature_std
                + feature_mean
            )

            raw_val = (
                F_val
                * feature_std
                + feature_mean
            )

            raw_test = (
                F_test
                * feature_std
                + feature_mean
            )

            metadata[
                "reconstruction_mode"
            ] = "inverse_standardisation"

            metadata[
                "mean_key"
            ] = mean_key

            metadata[
                "std_key"
            ] = std_key

        optional_identity = {}

        for key in [
            "case_id_train",
            "case_id_val",
            "case_id_test",
            "train_idx",
            "val_idx",
            "test_idx",
        ]:
            if key in data.files:
                optional_identity[
                    key
                ] = np.asarray(
                    data[key]
                )

    x_full = np.vstack(
        [
            raw_train,
            raw_val,
            raw_test,
        ]
    )

    y_full = np.vstack(
        [
            y_train,
            y_val,
            y_test,
        ]
    )

    if (
        x_full.shape
        != (
            EXPECTED_CASE_COUNT,
            expected_features,
        )
    ):
        raise ValueError(
            f"{path}: unexpected X shape "
            f"{x_full.shape}"
        )

    if (
        y_full.shape
        != (
            EXPECTED_CASE_COUNT,
            4,
        )
    ):
        raise ValueError(
            f"{path}: unexpected y shape "
            f"{y_full.shape}"
        )

    if not np.all(
        np.isfinite(
            x_full
        )
    ):
        raise FloatingPointError(
            f"{path}: non-finite raw features."
        )

    if not np.all(
        np.isfinite(
            y_full
        )
    ):
        raise FloatingPointError(
            f"{path}: non-finite targets."
        )

    metadata[
        "optional_identity"
    ] = optional_identity

    return (
        x_full,
        y_full,
        metadata,
    )


def verify_canonical_alignment(
    y_78: np.ndarray,
    y_92: np.ndarray,
    metadata_78: dict[str, Any],
    metadata_92: dict[str, Any],
) -> None:
    """Confirm that canonical concatenation order is identical."""

    if not np.array_equal(
        y_78,
        y_92,
    ):
        raise RuntimeError(
            "STOP: 78D and 92D canonical target "
            "ordering differs."
        )

    identity_78 = metadata_78[
        "optional_identity"
    ]

    identity_92 = metadata_92[
        "optional_identity"
    ]

    for key in sorted(
        set(identity_78)
        & set(identity_92)
    ):
        if not np.array_equal(
            identity_78[key],
            identity_92[key],
        ):
            raise RuntimeError(
                "STOP: 78D and 92D canonical "
                f"identifier differs: {key}"
            )


def load_split(
    split_root: Path,
    seed: int,
) -> tuple[
    np.ndarray,
    np.ndarray,
    np.ndarray,
]:

    path = (
        split_root
        / f"seed_{seed}_split.npz"
    )

    if not path.is_file():
        raise FileNotFoundError(
            path
        )

    with np.load(
        path,
        allow_pickle=False,
    ) as data:
        train_idx = np.asarray(
            data["train_idx"],
            dtype=np.int64,
        )

        val_idx = np.asarray(
            data["val_idx"],
            dtype=np.int64,
        )

        test_idx = np.asarray(
            data["test_idx"],
            dtype=np.int64,
        )

    if (
        len(train_idx)
        != N_TRAIN
        or len(val_idx)
        != N_VAL
        or len(test_idx)
        != N_TEST
    ):
        raise RuntimeError(
            f"Seed {seed}: split-size mismatch."
        )

    combined = np.concatenate(
        [
            train_idx,
            val_idx,
            test_idx,
        ]
    )

    if (
        len(
            np.unique(
                combined
            )
        )
        != EXPECTED_CASE_COUNT
    ):
        raise RuntimeError(
            f"Seed {seed}: overlap or omission "
            "in split indices."
        )

    if (
        np.min(combined) < 0
        or np.max(combined)
        >= EXPECTED_CASE_COUNT
    ):
        raise RuntimeError(
            f"Seed {seed}: out-of-range index."
        )

    return (
        train_idx,
        val_idx,
        test_idx,
    )


def clip_prediction(
    prediction: np.ndarray,
) -> np.ndarray:

    return np.clip(
        np.asarray(
            prediction,
            dtype=np.float64,
        ),
        0.0,
        0.5,
    )


def mse(
    truth: np.ndarray,
    prediction: np.ndarray,
) -> float:

    error = (
        np.asarray(
            prediction
        )
        - np.asarray(
            truth
        )
    )

    return float(
        np.mean(
            error ** 2
        )
    )


def mae(
    truth: np.ndarray,
    prediction: np.ndarray,
) -> float:

    return float(
        np.mean(
            np.abs(
                np.asarray(
                    prediction
                )
                - np.asarray(
                    truth
                )
            )
        )
    )


def calculate_metrics(
    truth: np.ndarray,
    prediction: np.ndarray,
) -> dict[str, float]:

    truth = np.asarray(
        truth,
        dtype=np.float64,
    )

    prediction = np.asarray(
        prediction,
        dtype=np.float64,
    )

    error = (
        prediction
        - truth
    )

    damaged = (
        truth > 1e-12
    )

    zero = (
        truth <= 1e-12
    )

    high = (
        truth > 0.20
    )

    high_bias = float(
        np.mean(
            error[
                high
            ]
        )
    )

    return {
        "test_mae": float(
            np.mean(
                np.abs(
                    error
                )
            )
        ),
        "test_rmse": float(
            np.sqrt(
                np.mean(
                    error ** 2
                )
            )
        ),
        "test_bias": float(
            np.mean(
                error
            )
        ),
        "damaged_entry_mae": float(
            np.mean(
                np.abs(
                    error[
                        damaged
                    ]
                )
            )
        ),
        "zero_damage_mae": float(
            np.mean(
                np.abs(
                    error[
                        zero
                    ]
                )
            )
        ),
        "high_damage_mae": float(
            np.mean(
                np.abs(
                    error[
                        high
                    ]
                )
            )
        ),
        "high_damage_bias": (
            high_bias
        ),
        "high_damage_abs_bias": (
            abs(
                high_bias
            )
        ),
        "high_damage_underestimation_ratio": float(
            np.mean(
                prediction[
                    high
                ]
                < truth[
                    high
                ]
            )
        ),
        "high_damage_n": int(
            np.sum(
                high
            )
        ),
    }


def damage_bins(
    seed: int,
    truth: np.ndarray,
    prediction: np.ndarray,
) -> list[
    dict[str, Any]
]:

    bins = {
        "zero": (
            truth <= 1e-12
        ),
        "low": (
            (truth > 1e-12)
            & (truth <= 0.10)
        ),
        "medium": (
            (truth > 0.10)
            & (truth <= 0.20)
        ),
        "high": (
            truth > 0.20
        ),
    }

    rows = []

    for name, mask in (
        bins.items()
    ):
        if not np.any(
            mask
        ):
            raise RuntimeError(
                f"Seed {seed}: empty damage bin {name}."
            )

        y_true = truth[
            mask
        ]

        y_pred = prediction[
            mask
        ]

        error = (
            y_pred
            - y_true
        )

        rows.append(
            {
                "seed": seed,
                "descriptor_set": (
                    "oracle_full"
                ),
                "model": (
                    "rbf_svr"
                ),
                "damage_bin": name,
                "n_entries": int(
                    np.sum(
                        mask
                    )
                ),
                "mae": float(
                    np.mean(
                        np.abs(
                            error
                        )
                    )
                ),
                "rmse": float(
                    np.sqrt(
                        np.mean(
                            error ** 2
                        )
                    )
                ),
                "bias": float(
                    np.mean(
                        error
                    )
                ),
                "mean_true": float(
                    np.mean(
                        y_true
                    )
                ),
                "mean_prediction": float(
                    np.mean(
                        y_pred
                    )
                ),
                "underestimation_ratio": (
                    np.nan
                    if name
                    == "zero"
                    else float(
                        np.mean(
                            y_pred
                            < y_true
                        )
                    )
                ),
            }
        )

    return rows


def select_svr(
    seed: int,
    x_train: np.ndarray,
    y_train: np.ndarray,
    x_val: np.ndarray,
    y_val: np.ndarray,
    n_jobs: int,
) -> tuple[
    MultiOutputRegressor,
    dict[str, Any],
    list[
        dict[str, Any]
    ],
]:

    best_model = None
    best_row = None

    candidate_rows = []

    total = (
        len(
            SVR_C_VALUES
        )
        * len(
            SVR_GAMMA_VALUES
        )
        * len(
            SVR_EPSILON_VALUES
        )
    )

    counter = 0

    for C in SVR_C_VALUES:
        for gamma in (
            SVR_GAMMA_VALUES
        ):
            for epsilon in (
                SVR_EPSILON_VALUES
            ):
                counter += 1

                estimator = (
                    MultiOutputRegressor(
                        SVR(
                            kernel="rbf",
                            C=C,
                            gamma=gamma,
                            epsilon=epsilon,
                            tol=1e-4,
                            cache_size=1024,
                        ),
                        n_jobs=n_jobs,
                    )
                )

                start = (
                    time.perf_counter()
                )

                estimator.fit(
                    x_train,
                    y_train,
                )

                fit_seconds = float(
                    time.perf_counter()
                    - start
                )

                val_prediction = (
                    clip_prediction(
                        estimator.predict(
                            x_val
                        )
                    )
                )

                support_counts = [
                    int(
                        len(
                            model.support_
                        )
                    )
                    for model
                    in estimator.estimators_
                ]

                gamma_label = (
                    f"{gamma:g}"
                    .replace(
                        ".",
                        "p",
                    )
                )

                candidate = (
                    f"rbf_svr_C_{C:g}"
                    f"_gamma_{gamma_label}"
                    f"_eps_{epsilon:g}"
                )

                row = {
                    "seed": seed,
                    "descriptor_set": (
                        "oracle_full"
                    ),
                    "candidate": (
                        candidate
                    ),
                    "C": float(
                        C
                    ),
                    "gamma": float(
                        gamma
                    ),
                    "epsilon": float(
                        epsilon
                    ),
                    "val_mse": mse(
                        y_val,
                        val_prediction,
                    ),
                    "val_mae": mae(
                        y_val,
                        val_prediction,
                    ),
                    "fit_seconds": (
                        fit_seconds
                    ),
                    "mean_support_vector_ratio": float(
                        np.mean(
                            support_counts
                        )
                        / x_train.shape[0]
                    ),
                    "selected": False,
                }

                candidate_rows.append(
                    row
                )

                if (
                    best_row is None
                ):
                    best_row = (
                        row.copy()
                    )

                    best_model = (
                        estimator
                    )

                else:
                    current_key = (
                        row[
                            "val_mse"
                        ],
                        row[
                            "candidate"
                        ],
                    )

                    best_key = (
                        best_row[
                            "val_mse"
                        ],
                        best_row[
                            "candidate"
                        ],
                    )

                    if (
                        current_key
                        < best_key
                    ):
                        best_row = (
                            row.copy()
                        )

                        best_model = (
                            estimator
                        )

                if (
                    counter % 15
                    == 0
                    or counter
                    == total
                ):
                    print(
                        f"    92D SVR progress: "
                        f"{counter}/{total}"
                    )

    if (
        best_model is None
        or best_row is None
    ):
        raise RuntimeError(
            f"Seed {seed}: SVR selection failed."
        )

    for row in (
        candidate_rows
    ):
        row[
            "selected"
        ] = (
            row[
                "candidate"
            ]
            == best_row[
                "candidate"
            ]
        )

    return (
        best_model,
        best_row,
        candidate_rows,
    )


def confidence_interval(
    values: np.ndarray,
) -> tuple[
    float,
    float,
]:

    values = np.asarray(
        values,
        dtype=np.float64,
    )

    mean_value = float(
        np.mean(
            values
        )
    )

    if len(
        values
    ) < 2:
        return (
            mean_value,
            mean_value,
        )

    standard_error = float(
        np.std(
            values,
            ddof=1,
        )
        / math.sqrt(
            len(
                values
            )
        )
    )

    critical = float(
        student_t.ppf(
            0.975,
            df=(
                len(
                    values
                )
                - 1
            ),
        )
    )

    margin = (
        critical
        * standard_error
    )

    return (
        mean_value
        - margin,
        mean_value
        + margin,
    )


