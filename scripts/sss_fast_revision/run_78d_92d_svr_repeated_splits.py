"""
10-seed paired information-availability comparison:

78D signal-derived-with-ground RBF-SVR
vs
92D oracle_full / privileged-information RBF-SVR

Design
------
- Reuse EXACTLY the ten split files generated by the previous
  78D Ridge-vs-SVR repeated-split experiment.
- Reuse the already-frozen 78D seed-level SVR results.
- Train only the 92D representation in this script.
- Per-seed StandardScaler is fitted on that seed's 92D training fold only.
- Same frozen 75-candidate RBF-SVR grid as the 78D experiment.
- Hyperparameters selected using clipped validation MSE only.
- Test evaluated only after validation selection.

Scientific question
-------------------
Does privileged simulation information provide a stable performance
advantage over the 78D deployable/signal-derived representation
when estimator flexibility is held constant?
"""

