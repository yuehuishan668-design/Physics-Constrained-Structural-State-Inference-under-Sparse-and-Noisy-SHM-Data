def _numeric_array(
    data: Any,
    key: str,
) -> np.ndarray:
    return np.asarray(
        data[key],
        dtype=np.float64,
    )


def _find_feature_vector(
    data: Any,
    exact_names: list[str],
    keyword: str,
) -> tuple[str, np.ndarray] | None:
    """
    Find a 78-dimensional numeric mean/std vector.

    First try explicit common names; otherwise search numeric
    one-dimensional arrays whose name contains the keyword.
    """

    for key in exact_names:
        if key in data.files:
            array = np.asarray(data[key])

            if (
                array.ndim == 1
                and array.shape[0]
                == EXPECTED_FEATURE_COUNT
                and np.issubdtype(
                    array.dtype,
                    np.number,
                )
            ):
                return (
                    key,
                    np.asarray(
                        array,
                        dtype=np.float64,
                    ),
                )

    candidates = []

    for key in data.files:
        if keyword not in key.lower():
            continue

        try:
            array = np.asarray(data[key])
        except Exception:
            continue

        if (
            array.ndim == 1
            and array.shape[0]
            == EXPECTED_FEATURE_COUNT
            and np.issubdtype(
                array.dtype,
                np.number,
            )
        ):
            candidates.append(
                (
                    key,
                    np.asarray(
                        array,
                        dtype=np.float64,
                    ),
                )
            )

    if len(candidates) == 1:
        return candidates[0]

    return None


def load_full_raw_dataset(
    path: Path,
) -> tuple[
    np.ndarray,
    np.ndarray,
    dict[str, Any],
]:
    """
    Reconstruct the complete 3000-case raw 78D descriptor matrix.

    Preferred route:
        F_train_raw / F_val_raw / F_test_raw

    Fallback:
        invert the canonical standardisation using stored feature
        mean and standard deviation.

    We must NOT concatenate already-standardised F_train/F_val/F_test
    and directly random-split them, because that would preserve the
    original split's scaling and introduce preprocessing leakage.
    """

    if not path.is_file():
        raise FileNotFoundError(path)

    required = {
        "F_train",
        "F_val",
        "F_test",
        "y_train",
        "y_val",
        "y_test",
    }

    with np.load(
        path,
        allow_pickle=False,
    ) as data:

        missing = sorted(
            required - set(data.files)
        )

        if missing:
            raise KeyError(
                f"Missing required arrays: {missing}"
            )

        F_train = _numeric_array(
            data,
            "F_train",
        )
        F_val = _numeric_array(
            data,
            "F_val",
        )
        F_test = _numeric_array(
            data,
            "F_test",
        )

        y_train = _numeric_array(
            data,
            "y_train",
        )
        y_val = _numeric_array(
            data,
            "y_val",
        )
        y_test = _numeric_array(
            data,
            "y_test",
        )

        raw_keys = {
            "F_train_raw",
            "F_val_raw",
            "F_test_raw",
        }

        metadata: dict[str, Any] = {}

        if raw_keys.issubset(
            set(data.files)
        ):
            raw_train = _numeric_array(
                data,
                "F_train_raw",
            )
            raw_val = _numeric_array(
                data,
                "F_val_raw",
            )
            raw_test = _numeric_array(
                data,
                "F_test_raw",
            )

            reconstruction_mode = (
                "explicit_raw_arrays"
            )

        else:
            mean_result = (
                _find_feature_vector(
                    data,
                    exact_names=[
                        "feature_mean",
                        "feature_means",
                        "F_mean",
                        "train_feature_mean",
                        "mean",
                    ],
                    keyword="mean",
                )
            )

            std_result = (
                _find_feature_vector(
                    data,
                    exact_names=[
                        "feature_std",
                        "feature_stds",
                        "F_std",
                        "train_feature_std",
                        "std",
                    ],
                    keyword="std",
                )
            )

            if (
                mean_result is None
                or std_result is None
            ):
                raise RuntimeError(
                    "Could not recover raw descriptors. "
                    "Expected either F_*_raw arrays or "
                    "78-dimensional stored mean/std vectors.\n"
                    f"Available keys: {sorted(data.files)}"
                )

            mean_key, feature_mean = (
                mean_result
            )

            std_key, feature_std = (
                std_result
            )

            raw_train = (
                F_train
                * feature_std
                + feature_mean
            )

            raw_val = (
                F_val
                * feature_std
                + feature_mean
            )

            raw_test = (
                F_test
                * feature_std
                + feature_mean
            )

            reconstruction_mode = (
                "inverse_standardisation"
            )

            metadata[
                "mean_key"
            ] = mean_key

            metadata[
                "std_key"
            ] = std_key

    for name, array in {
        "F_train": F_train,
        "F_val": F_val,
        "F_test": F_test,
        "raw_train": raw_train,
        "raw_val": raw_val,
        "raw_test": raw_test,
        "y_train": y_train,
        "y_val": y_val,
        "y_test": y_test,
    }.items():
        if not np.all(
            np.isfinite(array)
        ):
            raise FloatingPointError(
                f"{name} contains non-finite values."
            )

    if (
        raw_train.shape
        != (
            N_TRAIN,
            EXPECTED_FEATURE_COUNT,
        )
    ):
        raise ValueError(
            f"Unexpected raw_train shape: "
            f"{raw_train.shape}"
        )

    if (
        raw_val.shape
        != (
            N_VAL,
            EXPECTED_FEATURE_COUNT,
        )
    ):
        raise ValueError(
            f"Unexpected raw_val shape: "
            f"{raw_val.shape}"
        )

    if (
        raw_test.shape
        != (
            N_TEST,
            EXPECTED_FEATURE_COUNT,
        )
    ):
        raise ValueError(
            f"Unexpected raw_test shape: "
            f"{raw_test.shape}"
        )

    x_full = np.vstack(
        [
            raw_train,
            raw_val,
            raw_test,
        ]
    )

    y_full = np.vstack(
        [
            y_train,
            y_val,
            y_test,
        ]
    )

    if (
        x_full.shape
        != (
            EXPECTED_CASE_COUNT,
            EXPECTED_FEATURE_COUNT,
        )
    ):
        raise ValueError(
            f"Unexpected full feature shape: "
            f"{x_full.shape}"
        )

    if (
        y_full.shape
        != (
            EXPECTED_CASE_COUNT,
            4,
        )
    ):
        raise ValueError(
            f"Unexpected full target shape: "
            f"{y_full.shape}"
        )

    metadata[
        "reconstruction_mode"
    ] = reconstruction_mode

    metadata[
        "n_cases"
    ] = int(
        x_full.shape[0]
    )

    metadata[
        "n_features"
    ] = int(
        x_full.shape[1]
    )

    return (
        x_full,
        y_full,
        metadata,
    )


def make_split(
    n_cases: int,
    seed: int,
) -> tuple[
    np.ndarray,
    np.ndarray,
    np.ndarray,
]:

    rng = np.random.default_rng(
        seed
    )

    permutation = rng.permutation(
        n_cases
    )

    train_idx = permutation[
        :N_TRAIN
    ]

    val_idx = permutation[
        N_TRAIN:
        N_TRAIN + N_VAL
    ]

    test_idx = permutation[
        N_TRAIN + N_VAL:
    ]

    if (
        len(train_idx) != N_TRAIN
        or len(val_idx) != N_VAL
        or len(test_idx) != N_TEST
    ):
        raise RuntimeError(
            "Split size check failed."
        )

    if (
        len(
            np.unique(
                np.concatenate(
                    [
                        train_idx,
                        val_idx,
                        test_idx,
                    ]
                )
            )
        )
        != n_cases
    ):
        raise RuntimeError(
            "Split overlap or omission detected."
        )

    return (
        train_idx,
        val_idx,
        test_idx,
    )


def clip_prediction(
    prediction: np.ndarray,
) -> np.ndarray:

    return np.clip(
        np.asarray(
            prediction,
            dtype=np.float64,
        ),
        0.0,
        0.5,
    )


def mse(
    truth: np.ndarray,
    prediction: np.ndarray,
) -> float:

    error = (
        np.asarray(prediction)
        - np.asarray(truth)
    )

    return float(
        np.mean(
            error ** 2
        )
    )


def mae(
    truth: np.ndarray,
    prediction: np.ndarray,
) -> float:

    return float(
        np.mean(
            np.abs(
                np.asarray(prediction)
                - np.asarray(truth)
            )
        )
    )


def calculate_metrics(
    truth: np.ndarray,
    prediction: np.ndarray,
) -> dict[str, float]:

    truth = np.asarray(
        truth,
        dtype=np.float64,
    )

    prediction = np.asarray(
        prediction,
        dtype=np.float64,
    )

    error = (
        prediction
        - truth
    )

    damaged = (
        truth > 1e-12
    )

    zero = (
        truth <= 1e-12
    )

    high = (
        truth > 0.20
    )

    if not np.any(
        damaged
    ):
        raise ValueError(
            "No damaged entries."
        )

    if not np.any(
        zero
    ):
        raise ValueError(
            "No zero-damage entries."
        )

    if not np.any(
        high
    ):
        raise ValueError(
            "No high-damage entries."
        )

    high_bias = float(
        np.mean(
            error[high]
        )
    )

    return {
        "test_mae": float(
            np.mean(
                np.abs(error)
            )
        ),
        "test_rmse": float(
            np.sqrt(
                np.mean(
                    error ** 2
                )
            )
        ),
        "test_bias": float(
            np.mean(error)
        ),
        "damaged_entry_mae": float(
            np.mean(
                np.abs(
                    error[damaged]
                )
            )
        ),
        "zero_damage_mae": float(
            np.mean(
                np.abs(
                    error[zero]
                )
            )
        ),
        "high_damage_mae": float(
            np.mean(
                np.abs(
                    error[high]
                )
            )
        ),
        "high_damage_bias": (
            high_bias
        ),
        "high_damage_abs_bias": (
            abs(
                high_bias
            )
        ),
        "high_damage_underestimation_ratio": float(
            np.mean(
                prediction[high]
                < truth[high]
            )
        ),
        "high_damage_n": int(
            np.sum(high)
        ),
    }


def calculate_damage_bins(
    seed: int,
    model_name: str,
    truth: np.ndarray,
    prediction: np.ndarray,
) -> list[dict[str, Any]]:

    bins = {
        "zero": (
            truth <= 1e-12
        ),
        "low": (
            (truth > 1e-12)
            & (truth <= 0.10)
        ),
        "medium": (
            (truth > 0.10)
            & (truth <= 0.20)
        ),
        "high": (
            truth > 0.20
        ),
    }

    rows = []

    for bin_name, mask in (
        bins.items()
    ):
        if not np.any(mask):
            raise ValueError(
                f"Seed {seed}: empty "
                f"damage bin {bin_name}."
            )

        y_true = truth[mask]
        y_pred = prediction[mask]

        error = (
            y_pred - y_true
        )

        rows.append(
            {
                "seed": seed,
                "model": model_name,
                "damage_bin": bin_name,
                "n_entries": int(
                    np.sum(mask)
                ),
                "mae": float(
                    np.mean(
                        np.abs(error)
                    )
                ),
                "rmse": float(
                    np.sqrt(
                        np.mean(
                            error ** 2
                        )
                    )
                ),
                "bias": float(
                    np.mean(error)
                ),
                "mean_true": float(
                    np.mean(
                        y_true
                    )
                ),
                "mean_prediction": float(
                    np.mean(
                        y_pred
                    )
                ),
                "underestimation_ratio": (
                    np.nan
                    if bin_name
                    == "zero"
                    else float(
                        np.mean(
                            y_pred
                            < y_true
                        )
                    )
                ),
            }
        )

    return rows


def select_ridge(
    seed: int,
    x_train: np.ndarray,
    y_train: np.ndarray,
    x_val: np.ndarray,
    y_val: np.ndarray,
) -> tuple[
    Ridge,
    dict[str, Any],
    list[dict[str, Any]],
]:

    best_model = None
    best_row = None
    candidate_rows = []

    for alpha in RIDGE_ALPHAS:

        model = Ridge(
            alpha=alpha,
            fit_intercept=True,
        )

        start = time.perf_counter()

        model.fit(
            x_train,
            y_train,
        )

        fit_seconds = float(
            time.perf_counter()
            - start
        )

        prediction = (
            clip_prediction(
                model.predict(
                    x_val
                )
            )
        )

        row = {
            "seed": seed,
            "model": "ridge",
            "candidate": (
                f"ridge_alpha_{alpha:g}"
            ),
            "alpha": float(alpha),
            "C": np.nan,
            "gamma": np.nan,
            "epsilon": np.nan,
            "val_mse": mse(
                y_val,
                prediction,
            ),
            "val_mae": mae(
                y_val,
                prediction,
            ),
            "fit_seconds": (
                fit_seconds
            ),
            "mean_support_vector_ratio": (
                np.nan
            ),
            "selected": False,
        }

        candidate_rows.append(
            row
        )

        if best_row is None:
            best_row = row.copy()
            best_model = model
        else:
            current_key = (
                row["val_mse"],
                row["candidate"],
            )

            best_key = (
                best_row[
                    "val_mse"
                ],
                best_row[
                    "candidate"
                ],
            )

            if current_key < best_key:
                best_row = row.copy()
                best_model = model

    if (
        best_model is None
        or best_row is None
    ):
        raise RuntimeError(
            "Ridge selection failed."
        )

    for row in candidate_rows:
        row["selected"] = (
            row["candidate"]
            == best_row[
                "candidate"
            ]
        )

    return (
        best_model,
        best_row,
        candidate_rows,
    )


def select_svr(
    seed: int,
    x_train: np.ndarray,
    y_train: np.ndarray,
    x_val: np.ndarray,
    y_val: np.ndarray,
    n_jobs: int,
) -> tuple[
    MultiOutputRegressor,
    dict[str, Any],
    list[dict[str, Any]],
]:

    best_model = None
    best_row = None
    candidate_rows = []

    candidate_number = 0

    total = (
        len(SVR_C_VALUES)
        * len(
            SVR_GAMMA_VALUES
        )
        * len(
            SVR_EPSILON_VALUES
        )
    )

    for C in SVR_C_VALUES:
        for gamma in (
            SVR_GAMMA_VALUES
        ):
            for epsilon in (
                SVR_EPSILON_VALUES
            ):

                candidate_number += 1

                model = (
                    MultiOutputRegressor(
                        SVR(
                            kernel="rbf",
                            C=C,
                            gamma=gamma,
                            epsilon=epsilon,
                            tol=1e-4,
                            cache_size=1024,
                        ),
                        n_jobs=n_jobs,
                    )
                )

                start = (
                    time.perf_counter()
                )

                model.fit(
                    x_train,
                    y_train,
                )

                fit_seconds = float(
                    time.perf_counter()
                    - start
                )

                prediction = (
                    clip_prediction(
                        model.predict(
                            x_val
                        )
                    )
                )

                support_counts = [
                    int(
                        len(
                            estimator.support_
                        )
                    )
                    for estimator
                    in model.estimators_
                ]

                gamma_label = (
                    f"{gamma:g}"
                    .replace(
                        ".",
                        "p",
                    )
                )

                candidate = (
                    f"rbf_svr_C_{C:g}"
                    f"_gamma_{gamma_label}"
                    f"_eps_{epsilon:g}"
                )

                row = {
                    "seed": seed,
                    "model": "rbf_svr",
                    "candidate": (
                        candidate
                    ),
                    "alpha": np.nan,
                    "C": float(C),
                    "gamma": float(
                        gamma
                    ),
                    "epsilon": float(
                        epsilon
                    ),
                    "val_mse": mse(
                        y_val,
                        prediction,
                    ),
                    "val_mae": mae(
                        y_val,
                        prediction,
                    ),
                    "fit_seconds": (
                        fit_seconds
                    ),
                    "mean_support_vector_ratio": float(
                        np.mean(
                            support_counts
                        )
                        / x_train.shape[0]
                    ),
                    "selected": False,
                }

                candidate_rows.append(
                    row
                )

                if best_row is None:
                    best_row = (
                        row.copy()
                    )
                    best_model = model
                else:
                    current_key = (
                        row["val_mse"],
                        row[
                            "candidate"
                        ],
                    )

                    best_key = (
                        best_row[
                            "val_mse"
                        ],
                        best_row[
                            "candidate"
                        ],
                    )

                    if (
                        current_key
                        < best_key
                    ):
                        best_row = (
                            row.copy()
                        )
                        best_model = (
                            model
                        )

                if (
                    candidate_number
                    % 15 == 0
                    or candidate_number
                    == total
                ):
                    print(
                        f"    SVR progress: "
                        f"{candidate_number}/"
                        f"{total}"
                    )

    if (
        best_model is None
        or best_row is None
    ):
        raise RuntimeError(
            "SVR selection failed."
        )

    for row in candidate_rows:
        row["selected"] = (
            row["candidate"]
            == best_row[
                "candidate"
            ]
        )

    return (
        best_model,
        best_row,
        candidate_rows,
    )


def confidence_interval(
    values: np.ndarray,
    confidence: float = 0.95,
) -> tuple[
    float,
    float,
]:

    values = np.asarray(
        values,
        dtype=np.float64,
    )

    n = len(values)

    mean_value = float(
        np.mean(values)
    )

    if n < 2:
        return (
            mean_value,
            mean_value,
        )

    standard_error = float(
        np.std(
            values,
            ddof=1,
        )
        / math.sqrt(n)
    )

    critical = float(
        student_t.ppf(
            (
                1.0
                + confidence
            )
            / 2.0,
            df=n - 1,
        )
    )

    margin = (
        critical
        * standard_error
    )

    return (
        mean_value - margin,
        mean_value + margin,
    )


