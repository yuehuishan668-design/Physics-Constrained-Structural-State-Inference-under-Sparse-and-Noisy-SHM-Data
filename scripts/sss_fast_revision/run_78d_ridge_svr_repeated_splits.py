"""
10-seed paired repeated-split robustness comparison:

78D signal-derived-with-ground descriptors
    Ridge
        vs
    RBF-SVR

Protocol
--------
- Use all 3000 cases.
- Ten deterministic random 70/15/15 splits.
- Feature standardisation is re-fitted on EACH seed's training fold only.
- Ridge and SVR use exactly the same split within each seed.
- Hyperparameters are selected by clipped validation MSE only.
- Test is evaluated only after validation selection.
- Predictions are clipped to [0, 0.5].
- SVR uses the previously frozen 75-candidate search grid.

This experiment is separate from the historical fixed-split protocol.
Do not numerically mix fixed-split and repeated-split metrics as though
they were generated by the same evaluation design.
"""

