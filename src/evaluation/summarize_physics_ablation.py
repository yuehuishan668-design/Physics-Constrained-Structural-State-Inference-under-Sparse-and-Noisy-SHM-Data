"""
Summarize physics feature ablation results.

English:
This script reads the ablation comparison CSV generated by
run_physics_feature_ablation.py, then produces paper-ready summary tables
and diagnostic figures.

中文：
本脚本读取 run_physics_feature_ablation.py 生成的消融实验汇总 CSV，
然后生成论文可用的结果表、特征集贡献分析表和诊断图。
"""

from __future__ import annotations

import argparse
from pathlib import Path
from typing import List

import numpy as np
import pandas as pd
import matplotlib.pyplot as plt


# 数值列。部分列可能是 not_available，因此后面需要安全转换。
NUMERIC_COLUMNS = [
    "n_features",
    "best_val_mse",
    "test_mse",
    "test_mae",
    "test_rmse",
    "negative_prediction_ratio",
    "mean_prediction_on_zero_entries",
    "mae_on_damaged_entries",
    "mean_true_damage",
    "mean_pred_damage",
]


def parse_args() -> argparse.Namespace:
    """
    English:
    Parse command line arguments.

    中文：
    解析终端命令参数。
    """
    parser = argparse.ArgumentParser(
        description="Summarize physics feature ablation results."
    )

    parser.add_argument(
        "--comparison-csv",
        type=Path,
        required=True,
        help="Path to ablation_model_comparison.csv.",
    )

    parser.add_argument(
        "--output-dir",
        type=Path,
        required=True,
        help="Directory for output summary tables.",
    )

    parser.add_argument(
        "--figures-dir",
        type=Path,
        required=True,
        help="Directory for output summary figures.",
    )

    parser.add_argument(
        "--top-k",
        type=int,
        default=20,
        help="Number of top rows to print and save.",
    )

    return parser.parse_args()


def safe_numeric_conversion(df: pd.DataFrame) -> pd.DataFrame:
    """
    English:
    Convert known metric columns into numeric values.
    Invalid strings such as 'not_available' become NaN.

    中文：
    将已知指标列安全转换为数值。
    如果原始内容是 'not_available' 这类字符串，则转换为 NaN。
    """
    df = df.copy()

    for col in NUMERIC_COLUMNS:
        if col in df.columns:
            df[col] = pd.to_numeric(df[col], errors="coerce")

    return df


def save_top_models(df: pd.DataFrame, output_dir: Path, top_k: int) -> pd.DataFrame:
    """
    English:
    Save the top-k models sorted by test MAE.

    中文：
    按测试集 MAE 从小到大排序，保存前 top-k 个模型。
    """
    top_df = df.sort_values("test_mae", ascending=True).head(top_k).copy()

    output_path = output_dir / "top_models_by_test_mae.csv"
    top_df.to_csv(output_path, index=False, encoding="utf-8-sig")

    return top_df


def save_best_by_feature_set(df: pd.DataFrame, output_dir: Path) -> pd.DataFrame:
    """
    English:
    For each feature set, keep the estimator with the lowest test MAE.

    中文：
    对每一种特征集，只保留测试集 MAE 最低的模型。
    """
    best_df = (
        df.sort_values("test_mae", ascending=True)
        .groupby("feature_set", as_index=False)
        .first()
    )

    best_df = best_df.sort_values("test_mae", ascending=True)

    output_path = output_dir / "best_estimator_per_feature_set.csv"
    best_df.to_csv(output_path, index=False, encoding="utf-8-sig")

    return best_df


def save_best_by_estimator(df: pd.DataFrame, output_dir: Path) -> pd.DataFrame:
    """
    English:
    For each estimator, keep its best feature-set configuration.

    中文：
    对每一种模型，只保留其表现最好的特征集组合。
    """
    best_df = (
        df.sort_values("test_mae", ascending=True)
        .groupby("estimator", as_index=False)
        .first()
    )

    best_df = best_df.sort_values("test_mae", ascending=True)

    output_path = output_dir / "best_feature_set_per_estimator.csv"
    best_df.to_csv(output_path, index=False, encoding="utf-8-sig")

    return best_df


def save_feature_contribution_table(
    best_by_feature: pd.DataFrame,
    output_dir: Path,
) -> pd.DataFrame:
    """
    English:
    Compare each feature set against the best full-feature baseline.

    中文：
    将每个特征集的最佳结果与 full 特征集结果对比，
    得到 MAE 增量和相对退化百分比。
    """
    best_by_feature = best_by_feature.copy()

    full_rows = best_by_feature[best_by_feature["feature_set"] == "full"]

    if len(full_rows) == 0:
        raise ValueError("Cannot find feature_set == 'full' in the comparison table.")

    full_mae = float(full_rows.iloc[0]["test_mae"])
    full_rmse = float(full_rows.iloc[0]["test_rmse"])

    best_by_feature["delta_mae_vs_full"] = best_by_feature["test_mae"] - full_mae
    best_by_feature["delta_rmse_vs_full"] = best_by_feature["test_rmse"] - full_rmse

    best_by_feature["relative_mae_increase_pct"] = (
        best_by_feature["delta_mae_vs_full"] / full_mae * 100.0
    )

    output_path = output_dir / "feature_set_contribution_vs_full.csv"
    best_by_feature.to_csv(output_path, index=False, encoding="utf-8-sig")

    return best_by_feature


def plot_metric_bar(
    df: pd.DataFrame,
    metric: str,
    output_path: Path,
    title: str,
) -> None:
    """
    English:
    Draw a grouped bar chart for one metric.

    中文：
    绘制不同特征集和不同模型在某一指标上的对比柱状图。
    """
    pivot = df.pivot_table(
        index="feature_set",
        columns="estimator",
        values=metric,
        aggfunc="min",
    )

    pivot = pivot.sort_values(by=pivot.columns.tolist(), ascending=True)

    ax = pivot.plot(kind="bar", figsize=(12, 6))
    ax.set_title(title)
    ax.set_xlabel("Feature set")
    ax.set_ylabel(metric)
    ax.grid(axis="y", linestyle="--", alpha=0.4)
    plt.xticks(rotation=35, ha="right")
    plt.tight_layout()
    plt.savefig(output_path, dpi=300)
    plt.close()


def plot_true_pred_damage(df: pd.DataFrame, output_path: Path) -> None:
    """
    English:
    Plot mean true damage versus mean predicted damage.

    中文：
    绘制不同实验组合下的真实平均损伤值与预测平均损伤值。
    如果预测均值明显偏低，说明模型存在低估损伤的问题。
    """
    valid = df.dropna(subset=["mean_true_damage", "mean_pred_damage"]).copy()

    fig, ax = plt.subplots(figsize=(7, 7))
    ax.scatter(valid["mean_true_damage"], valid["mean_pred_damage"])

    min_value = min(valid["mean_true_damage"].min(), valid["mean_pred_damage"].min())
    max_value = max(valid["mean_true_damage"].max(), valid["mean_pred_damage"].max())

    ax.plot([min_value, max_value], [min_value, max_value], linestyle="--")

    ax.set_title("Mean true damage vs mean predicted damage")
    ax.set_xlabel("Mean true damage")
    ax.set_ylabel("Mean predicted damage")
    ax.grid(True, linestyle="--", alpha=0.4)
    plt.tight_layout()
    plt.savefig(output_path, dpi=300)
    plt.close()


def write_markdown_report(
    top_df: pd.DataFrame,
    best_by_feature: pd.DataFrame,
    best_by_estimator: pd.DataFrame,
    contribution_df: pd.DataFrame,
    output_path: Path,
) -> None:
    """
    English:
    Write a concise paper-oriented result summary.

    中文：
    生成一个面向论文写作的结果摘要 Markdown 文件。
    """
    best_row = top_df.iloc[0]

    lines: List[str] = []

    lines.append("# Physics Feature Ablation Summary")
    lines.append("")
    lines.append("## 1. Overall best model")
    lines.append("")
    lines.append(
        f"- Best configuration: `{best_row['feature_set']} + {best_row['estimator']}`"
    )
    lines.append(f"- Test MAE: `{best_row['test_mae']:.6f}`")
    lines.append(f"- Test RMSE: `{best_row['test_rmse']:.6f}`")
    lines.append(f"- Number of features: `{int(best_row['n_features'])}`")
    lines.append(f"- Mean true damage: `{best_row['mean_true_damage']:.6f}`")
    lines.append(f"- Mean predicted damage: `{best_row['mean_pred_damage']:.6f}`")
    lines.append("")

    lines.append("## 2. Best estimator for each feature set")
    lines.append("")
    lines.append(
        best_by_feature[
            [
                "feature_set",
                "estimator",
                "n_features",
                "test_mae",
                "test_rmse",
                "mean_true_damage",
                "mean_pred_damage",
            ]
        ].to_markdown(index=False)
    )
    lines.append("")

    lines.append("## 3. Best feature set for each estimator")
    lines.append("")
    lines.append(
        best_by_estimator[
            [
                "estimator",
                "feature_set",
                "n_features",
                "test_mae",
                "test_rmse",
                "mean_true_damage",
                "mean_pred_damage",
            ]
        ].to_markdown(index=False)
    )
    lines.append("")

    lines.append("## 4. Feature contribution relative to full feature set")
    lines.append("")
    lines.append(
        contribution_df[
            [
                "feature_set",
                "estimator",
                "n_features",
                "test_mae",
                "delta_mae_vs_full",
                "relative_mae_increase_pct",
            ]
        ].to_markdown(index=False)
    )
    lines.append("")

    lines.append("## 5. Preliminary interpretation")
    lines.append("")
    lines.append(
        "- If the full feature set ranks first, the result supports the value of combining multiple physics-informed response descriptors."
    )
    lines.append(
        "- If no_meta is close to full, the metadata contribution is limited and the main predictive information comes from structural response features."
    )
    lines.append(
        "- If simple regularized linear models outperform tree models, the current dataset is more consistent with a low-sample, noisy, weakly nonlinear regression setting."
    )
    lines.append(
        "- If mean predicted damage is lower than mean true damage, the model still has a damage-underestimation bias, especially for larger degradation cases."
    )
    lines.append("")

    output_path.write_text("\n".join(lines), encoding="utf-8")


def main() -> None:
    args = parse_args()

    args.output_dir.mkdir(parents=True, exist_ok=True)
    args.figures_dir.mkdir(parents=True, exist_ok=True)

    if not args.comparison_csv.exists():
        raise FileNotFoundError(f"Comparison CSV not found: {args.comparison_csv}")

    df = pd.read_csv(args.comparison_csv)
    df = safe_numeric_conversion(df)

    required_columns = ["feature_set", "estimator", "test_mae", "test_rmse"]
    missing_columns = [col for col in required_columns if col not in df.columns]

    if missing_columns:
        raise ValueError(f"Missing required columns: {missing_columns}")

    df = df.dropna(subset=["test_mae", "test_rmse"]).copy()

    top_df = save_top_models(df, args.output_dir, args.top_k)
    best_by_feature = save_best_by_feature_set(df, args.output_dir)
    best_by_estimator = save_best_by_estimator(df, args.output_dir)
    contribution_df = save_feature_contribution_table(best_by_feature, args.output_dir)

    plot_metric_bar(
        df=df,
        metric="test_mae",
        output_path=args.figures_dir / "test_mae_by_feature_set_and_estimator.png",
        title="Test MAE by feature set and estimator",
    )

    plot_metric_bar(
        df=df,
        metric="test_rmse",
        output_path=args.figures_dir / "test_rmse_by_feature_set_and_estimator.png",
        title="Test RMSE by feature set and estimator",
    )

    plot_true_pred_damage(
        df=df,
        output_path=args.figures_dir / "mean_true_vs_pred_damage.png",
    )

    report_path = args.output_dir / "paper_result_summary.md"

    write_markdown_report(
        top_df=top_df,
        best_by_feature=best_by_feature,
        best_by_estimator=best_by_estimator,
        contribution_df=contribution_df,
        output_path=report_path,
    )

    print("Physics ablation summary completed.")
    print(f"Input CSV: {args.comparison_csv}")
    print(f"Output tables: {args.output_dir}")
    print(f"Output figures: {args.figures_dir}")
    print(f"Markdown report: {report_path}")
    print("")
    print("Top models by Test MAE:")
    print(
        top_df[
            [
                "feature_set",
                "estimator",
                "n_features",
                "test_mae",
                "test_rmse",
                "mean_true_damage",
                "mean_pred_damage",
            ]
        ].to_string(index=False)
    )


if __name__ == "__main__":
    main()
    